#!/usr/bin/env python3
"""
sync_web_prompt.py — regenerate the web demo's system prompt from the style file.

The shipped style (output-styles/say-less.md) is the single source of truth. The
web demo can't read it at runtime (it deploys to a different repo), so the body
is copied into web/api/say-less-system.md at build time. Run this whenever the
style changes, and commit the result.

    python3 benchmark/sync_web_prompt.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "output-styles", "say-less.md")
DST = os.path.join(ROOT, "web", "api", "say-less-system.md")

BANNER = (
    "<!-- GENERATED by benchmark/sync_web_prompt.py from output-styles/say-less.md.\n"
    "     Do not edit by hand: edit the style file and re-run the script. -->\n\n"
)


def strip_frontmatter(text):
    """Drop the YAML frontmatter; the API takes the body as a system prompt."""
    if not text.startswith("---"):
        return text
    end = text.find("\n---", 3)
    if end == -1:
        return text
    return text[text.find("\n", end + 1) + 1:].lstrip("\n")


def main():
    with open(SRC) as f:
        body = strip_frontmatter(f.read())
    out = BANNER + body
    changed = True
    if os.path.exists(DST):
        with open(DST) as f:
            changed = f.read() != out
    with open(DST, "w") as f:
        f.write(out)
    words = len(body.split())
    print(f"{'updated' if changed else 'unchanged'}: {os.path.relpath(DST, ROOT)} "
          f"({words} words from {os.path.relpath(SRC, ROOT)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
